package generator_test

import (
	"encoding/json"
	"path/filepath"
	"strings"
	"testing"

	"github.com/dreamsxin/go-kit/v2/cmd/microgen/internal/generator"
)

// TestGenerateFull_OwnershipMarkers pins the ownership contract of a generated
// project: every artifact the manifest declares as generator-owned carries a
// machine-readable generated marker on its first line, and every file microgen
// writes once and never touches again carries none. A new template that skips
// its marker fails here, and so does a scaffold that wrongly claims one.
func TestGenerateFull_OwnershipMarkers(t *testing.T) {
	outDir := newTmpDir(t)
	project := parseIDLProject(t, "basic.go")

	gen := mustNewGenerator(t, generator.Options{
		OutputDir:       outDir,
		ImportPath:      "example.com/basic",
		Protocols:       []string{"http", "grpc"},
		DBDriver:        "sqlite",
		WithConfig:      true,
		WithDocs:        true,
		WithTests:       true,
		WithModel:       true,
		WithDB:          true,
		WithOpenAPI:     true,
		WithInteraction: true,
	})
	if err := gen.GenerateIR(project); err != nil {
		t.Fatalf("GenerateIR: %v", err)
	}

	var manifest struct {
		Artifacts []string `json:"artifacts"`
	}
	manifestBytes := readFile(t, filepath.Join(outDir, ".microgen", "manifest.json"))
	if err := json.Unmarshal([]byte(manifestBytes), &manifest); err != nil {
		t.Fatalf("parse manifest: %v", err)
	}
	if len(manifest.Artifacts) == 0 {
		t.Fatal("manifest declares no artifacts")
	}

	goHeader := "// Code generated by microgen. DO NOT EDIT."
	for _, artifact := range manifest.Artifacts {
		path := filepath.Join(outDir, filepath.FromSlash(artifact))
		switch {
		case strings.HasSuffix(artifact, ".go") || strings.HasSuffix(artifact, ".proto"):
			assertFirstLine(t, path, goHeader)
		case strings.HasSuffix(artifact, "client.ts"):
			assertFirstLine(t, path, "/* Code generated by microgen. DO NOT EDIT. */")
		}
	}

	// Files written once are the user's; none of them may claim the marker.
	for _, rel := range []string{
		"cmd/main.go",
		"cmd/custom_routes.go",
		"service/userservice/service.go",
		"endpoint/userservice/custom_chain.go",
		"model/user.go",
		"config/custom.go",
		"config/config.yaml",
		"README.md",
	} {
		mustNotContain(t, filepath.Join(outDir, filepath.FromSlash(rel)), "Code generated")
	}
}

// assertFirstLine asserts the file's first line equals want.
func assertFirstLine(t *testing.T, path, want string) {
	t.Helper()
	content := readFile(t, path)
	first := content
	if idx := strings.IndexByte(content, '\n'); idx >= 0 {
		first = content[:idx]
	}
	if first != want {
		t.Errorf("file %q first line = %q, want %q", path, first, want)
	}
}
